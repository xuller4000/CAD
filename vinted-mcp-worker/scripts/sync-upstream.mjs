// Holt googlarz/vinted-mcp-cli und baut daraus src/vendor/ (ops, endpoints, dispatch, Tool-Definitionen).
// Node-spezifische Teile (undici, Playwright) werden durch src/overrides/ ersetzt.
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoUrl = process.env.UPSTREAM_URL ?? 'https://github.com/googlarz/vinted-mcp-cli';
const ref = process.env.UPSTREAM_REF; // optional Tag/Branch
let up = process.env.UPSTREAM_DIR;

if (!up) {
  up = join(root, '.upstream');
  if (existsSync(join(up, '.git'))) {
    execFileSync('git', ['-C', up, 'fetch', '--depth=1', 'origin', ref ?? 'HEAD'], { stdio: 'inherit' });
    execFileSync('git', ['-C', up, 'reset', '--hard', 'FETCH_HEAD'], { stdio: 'inherit' });
  } else {
    const args = ['clone', '--depth=1', ...(ref ? ['--branch', ref] : []), repoUrl, up];
    execFileSync('git', args, { stdio: 'inherit', env: { ...process.env, GIT_LFS_SKIP_SMUDGE: '1' } });
  }
}

const src = join(up, 'src');
const out = join(root, 'src', 'vendor');
rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'client'), { recursive: true });

cpSync(join(src, 'ops'), join(out, 'ops'), { recursive: true });
for (const f of ['endpoints', 'types', 'catalog-html', 'cache', 'rate-limit']) {
  cpSync(join(src, 'client', `${f}.ts`), join(out, 'client', `${f}.ts`));
}
cpSync(join(src, 'dispatch.ts'), join(out, 'dispatch.ts'));
for (const f of ['session', 'browser']) cpSync(join(root, 'src', 'overrides', `${f}.ts`), join(out, 'client', `${f}.ts`));
cpSync(join(root, 'src', 'overrides', 'version.ts'), join(out, 'version.ts'));

// TOOLS, PROMPTS und der GetPrompt-Handler stehen in mcp.ts, das beim Import den Server startet.
const lines = readFileSync(join(src, 'mcp.ts'), 'utf8').split('\n');
const block = (startRe, endRe) => {
  const s = lines.findIndex((l) => startRe.test(l));
  if (s < 0) throw new Error(`upstream mcp.ts: ${startRe} nicht gefunden`);
  const e = lines.findIndex((l, i) => i > s && endRe.test(l));
  if (e < 0) throw new Error(`upstream mcp.ts: Ende zu ${startRe} nicht gefunden`);
  return lines.slice(s, e + 1).join('\n');
};
const tools = block(/^const TOOLS = \[/, /^\];/);
const prompts = block(/^const PROMPTS = \[/, /^\];/);
const getPrompt = block(/^\s*server\.setRequestHandler\(GetPromptRequestSchema/, /^\s{2}\}\);/);

writeFileSync(join(out, 'mcp-defs.ts'), `// AUTO-GENERATED by scripts/sync-upstream.mjs. Nicht editieren.
import { COUNTRIES } from './client/types.js';
export ${tools}
export ${prompts}
export function registerPromptHandler(server: any, GetPromptRequestSchema: any) {
${getPrompt.replace('async (req)', 'async (req: any)')}
}
`);

const sha = existsSync(join(up, '.git'))
  ? execFileSync('git', ['-C', up, 'rev-parse', '--short', 'HEAD']).toString().trim()
  : 'local';
writeFileSync(join(out, 'UPSTREAM'), `${repoUrl} @ ${sha}\n`);
console.log(`vendor synced from ${repoUrl} @ ${sha}`);
